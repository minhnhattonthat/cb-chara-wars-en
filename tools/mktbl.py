"""Generate tbl/jp.tbl from the font layout seen in VRAM (BG3 chars at VRAM $C000; code == tile number).

    python -X utf8 tools/mktbl.py   -> tbl/jp.tbl
Dakuten 8E / handakuten 8F precede the kana in the dialogue stream; 2-byte keys decode them to voiced kana.
"""
from pathlib import Path

ROWS = {
    0x20: " !\"#＃・&'()×+、ー。/",
    0x30: "0123456789:;<=>?",
    0x40: "©ABCDEFGHIJKLMNO",
    0x50: "PQRSTUVWXYZ[¥]^_",
    0x60: "あいうえおかきくけこさしすせそた",
    0x70: "ちつてとなにぬねのはひふへほまみ",
    0x80: "むめもやゆよらりるれろわをん",
    0x90: "アイウエオカキクケコサシスセソタ",
    0xA0: "チツテトナニヌネノハヒフヘホマミ",
    0xB0: "ムメモヤユヨラリルレロワヲン",
    0xC0: "ぁぃぅぇぉァィゥェォ",
    0xD0: "っゃゅょッャュョ",
}
VOICED = dict(zip("かきくけこさしすせそたちつてとはひふへほカキクケコサシスセソタチツテトハヒフヘホウ",
                  "がぎぐげござじずぜぞだぢづでどばびぶべぼガギグゲゴザジズゼゾダヂヅデドバビブベボヴ"))
SEMI = dict(zip("はひふへほハヒフヘホ", "ぱぴぷぺぽパピプペポ"))
# Kanji/icons at 08-1F read from the VRAM sheet; unsure ones left as [XX] until seen in context.
KANJI = {0x08: "子", 0x09: "分", 0x0A: "毛", 0x0B: "共", 0x0C: "用", 0x10: "♥", 0x18: "進", 0x19: "何", 0x1A: "品", 0x1B: "力", 0x1F: "店",
         # menu dakuten-row tiles (bank 0B menus): halfwidth marks keep them distinct from 8E/8F
         0xE1: "＿", 0xE3: "ﾞ", 0xE4: "ﾟ"}
CTRL = ["F7={yesno}", "F8={f8:1}", "FD={fd:1}", "FE={n}", "FF={end}",
        "0D={icon0D}", "0E={icon0E}", "0F={icon0F}"]  # LIFE gauge / [MAX] graphic tiles


def main():
    dec = {0x00: "　"}
    for base, s in ROWS.items():
        for i, ch in enumerate(s):
            if ch != " ":
                dec[base + i] = ch
    dec[0x8E], dec[0x8F] = "゛", "゜"
    dec.update(KANJI)
    lines = ["# CB Chara Wars dialogue table (generated by tools/mktbl.py; do not edit by hand)"]
    lines += CTRL
    rev = {v: k for k, v in dec.items()}
    for mark, table in ((0x8E, VOICED), (0x8F, SEMI)):
        for plain, voiced in table.items():
            if plain in rev:
                lines.append(f"{mark:02X}{rev[plain]:02X}={voiced}")
    lines += [f"{k:02X}={v}" for k, v in sorted(dec.items())]
    out = Path(__file__).resolve().parent.parent / "tbl" / "jp.tbl"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(lines) - 1} entries)")


if __name__ == "__main__":
    main()
